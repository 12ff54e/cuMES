#!/usr/bin/env python3
"""Generate the pressure supplement without modifying the original matrix."""

import argparse
import copy
import json

from generate import ROOT, encode, sha256

ORIGINAL_MANIFEST_SHA256 = "90f28299f35d97d577873620e030f2b88facf9eaa08114ba0aca981f9f90f776"
CASES = [
    ("16_solovev_pressure1000_linear", "Linear pressure, 1000 Pa on axis", [1000.0, -1000.0]),
    ("17_solovev_pressure5000_linear", "Linear pressure, 5000 Pa on axis", [5000.0, -5000.0]),
    ("18_solovev_pressure1000_quadratic", "Quadratic pressure, 1000 Pa on axis", [1000.0, -2000.0, 1000.0]),
]


def generate():
    original_bytes = (ROOT / "manifest.json").read_bytes()
    if sha256(original_bytes) != ORIGINAL_MANIFEST_SHA256:
        raise SystemExit("Original manifest changed; refusing to redefine the supplement's baseline.")
    original = json.loads(original_bytes)
    source = original["sources"]["solovev"]
    source_bytes = (ROOT / source["file"]).read_bytes()
    if sha256(source_bytes) != source["sha256"]:
        raise SystemExit("Pinned Solovev source hash changed.")
    base = json.loads(source_bytes)
    reference = next(case for case in original["cases"] if case["id"] == "00_solovev_reference")
    outputs = {}
    cases = []
    for case_id, title, coefficients in CASES:
        value = copy.deepcopy(base)
        value["am"] = coefficients
        assert {key for key in value if value[key] != base[key]} == {"am"}
        for key, control in original["common_stage_controls"].items():
            assert value[key] == control
        input_path = f"inputs/{case_id}.json"
        raw = encode(value)
        outputs[input_path] = raw
        cases.append({
            "id": case_id,
            "title": title,
            "input": input_path,
            "categories": ["finite_pressure_supplement", "pressure_amplitude", "pressure_profile"],
            "source": "solovev",
            "provenance": "generated_solovev_variation",
            "changes": [{"key": "am", "before": base["am"], "after": coefficients}],
            "notes": [
                "Only am changes from the pinned Solovev source; boundary, flux, iota, seeds, resolution, step and every stage control are retained.",
                "With the retained pres_scale=1, am is the pressure polynomial in SI Pa. The device profile multiplies it by mu0.",
            ],
            "central_pressure_pa": coefficients[0],
            "sha256": sha256(raw),
            "expected": copy.deepcopy(reference["expected"]),
        })
    supplement = {
        "schema": original["schema"],
        "matrix_kind": "finite_pressure_supplement",
        "declared_date": "2026-09-08",
        "supplements": {
            "manifest": "manifest.json",
            "sha256": ORIGINAL_MANIFEST_SHA256,
            "original_case_ids": [case["id"] for case in original["cases"]],
        },
        "selection": "Declared after the original sixteen-case screen exposed a pressure-unit coverage gap: its generated pressure variations surround a central pressure of only 0.125 Pa. These three finite-pressure inputs are fixed before their own solver runs. They address physical coverage, not selection by timing or convergence; retain every outcome.",
        "pressure_convention": {
            "input_units": "SI Pa with the retained pres_scale=1",
            "code": "include/cumes/config/profile_functions.hpp: eval_mass_profile multiplies the pressure polynomial by DeviceParams<T>::MU_0 * pres_scale; src/kernels/profiles_impl.cuh uploads that result to pres_H.",
        },
        "precision": original["precision"],
        "newton_policy": copy.deepcopy(original["newton_policy"]),
        "common_stage_controls": copy.deepcopy(original["common_stage_controls"]),
        "sources": {"solovev": copy.deepcopy(source)},
        "cases": cases,
    }
    outputs["pressure_manifest.json"] = encode(supplement)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated bytes without writing.")
    args = parser.parse_args()
    mismatch = []
    for name, raw in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != raw:
                mismatch.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    if mismatch:
        raise SystemExit("Generated content differs: " + ", ".join(mismatch))
    print("Checked" if args.check else "Generated", "3 pressure supplements; original manifest untouched")


if __name__ == "__main__":
    main()
